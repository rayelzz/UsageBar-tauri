function normalizeVisible(ids) {
  const out = [];
  for (const id of ids || []) {
    if (CATALOG_IDS.includes(id) && !out.includes(id)) out.push(id);
    if (out.length === SLOT_MAX) break;
  }
  return out.length ? out : DEFAULT_VISIBLE.slice();
}

