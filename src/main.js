function dockPath(w, h, edge) {
  if (edge === "floating") {
    const hh = h - gearAlong(edge);
    const r = Math.min(w, hh) / 2;
    return `M${r},0 H${w - r} A${r},${r} 0 0 1 ${w},${r} V${hh - r} A${r},${r} 0 0 1 ${w - r},${hh} H${r} A${r},${r} 0 0 1 0,${hh - r} V${r} A${r},${r} 0 0 1 ${r},0 Z`;
  }
  const vertical = edge === "left" || edge === "right";
  const bw = vertical ? w : w - gearAlong(edge);
  const bh = vertical ? h - gearAlong(edge) : h;
  const along = vertical ? bh : bw;
  const [f, r] = radii(bw, bh, along);
  const pad = 1;
  const a = S;
  const X = (t) => (edge === "right" ? w - t : t);
  const Yh = (t) => (edge === "top" ? t : h - t);
  if (vertical) {
    return [
      `M${X(-pad)},0`,
      `L${X(0)},0`,
      `C${X(0)},${a * f} ${X((1 - a) * f)},${f} ${X(f)},${f}`,
      `L${X(w - r)},${f}`,
      `C${X(w - r + K * r)},${f} ${X(w)},${f + r - K * r} ${X(w)},${f + r}`,
      `L${X(w)},${bh - f - r}`,
      `C${X(w)},${bh - f - r + K * r} ${X(w - r + K * r)},${bh - f} ${X(w - r)},${bh - f}`,
      `L${X(f)},${bh - f}`,
      `C${X((1 - a) * f)},${bh - f} ${X(0)},${bh - a * f} ${X(0)},${bh}`,
      `L${X(-pad)},${bh}`,
      "Z",
    ].join(" ");
  }
  return [
    `M0,${Yh(-pad)}`,
    `L0,${Yh(0)}`,
    `C${a * f},${Yh(0)} ${f},${Yh((1 - a) * f)} ${f},${Yh(f)}`,
    `L${f},${Yh(h - r)}`,
    `C${f},${Yh(h - r + K * r)} ${f + r - K * r},${Yh(h)} ${f + r},${Yh(h)}`,
    `L${bw - f - r},${Yh(h)}`,
    `C${bw - f - r + K * r},${Yh(h)} ${bw - f},${Yh(h - r + K * r)} ${bw - f},${Yh(h - r)}`,
    `L${bw - f},${Yh(f)}`,
    `C${bw - f},${Yh((1 - a) * f)} ${bw - a * f},${Yh(0)} ${bw},${Yh(0)}`,
    `L${bw},${Yh(-pad)}`,
    "Z",
  ].join(" ");
}

function gearCenter(w, h, edge) {
  const cross = GEAR_CARVE;
  switch (edge) {
    case "right":
      return { x: cross, y: h - GEAR_END };
    case "left":
      return { x: w - cross, y: h - GEAR_END };
    case "top":
      return { x: w - GEAR_END, y: h - cross };
    case "bottom":
      return { x: w - GEAR_END, y: cross };
    default:
      return { x: w / 2, y: h - GEAR_END };
  }
}

function padding(edge) {
  const g = gearAlong(edge);
  switch (edge) {
    case "right": return { t: 20, b: 20 + g, l: 6, r: 4 };
    case "left": return { t: 20, b: 20 + g, l: 4, r: 6 };
    case "top": return { t: 5, b: 7, l: 18, r: 12 + g };
    case "bottom": return { t: 7, b: 5, l: 18, r: 12 + g };
    default: return { t: 16, b: 16 + g, l: 5, r: 5 };
  }
}

function isVertical(edge) {
  return edge === "left" || edge === "right" || edge === "floating";
}

function isIcons() {
  return prefs.displayStyle === "icons";
}

function barSize(edge) {
  const n = slotCount();
  if (isIcons()) {
    const along = ICONS_BASE + ICONS_SLOT * n;
    return isVertical(edge) ? { w: ICONS_THICK, h: along } : { w: along, h: ICONS_THICK };
  }
  if (isVertical(edge)) return { w: BAR_THICK, h: BAR_PAD + BAR_SLOT * n + gearAlong(edge) };
  return { w: BAR_H_BASE + BAR_H_SLOT * n + gearAlong(edge), h: BAR_H_THICK };
}

function logicalMonitor(m) {
  const s = m.scaleFactor || 1;
  return {
    name: m.name || "",
    x: m.position.x / s,
    y: m.position.y / s,
    w: m.size.width / s,
    h: m.size.height / s,
    wx: m.workArea.position.x / s,
    wy: m.workArea.position.y / s,
    ww: m.workArea.size.width / s,
    wh: m.workArea.size.height / s,
    scale: s,
    raw: m,
  };
}

function clamp(v, lo, hi) {
  return Math.min(Math.max(v, lo), Math.max(lo, hi));
}

function nearest(frame, screen) {
  const right = Math.abs(frame.x + frame.w - (screen.x + screen.w));
  const left = Math.abs(frame.x - screen.x);
  const top = Math.abs(frame.y - screen.wy);
  const bottom = Math.abs(frame.y + frame.h - (screen.wy + screen.wh));
  const pairs = [
    ["right", right],
    ["left", left],
    ["top", top],
    ["bottom", bottom],
  ];
  pairs.sort((a, b) => a[1] - b[1]);
  return pairs[0][1] <= SNAP ? pairs[0][0] : "floating";
}

function gluedFrame(edge, size, along, screen) {
  if (edge === "right") {
    const y = clamp(along, screen.wy, screen.wy + screen.wh - size.h);
    return { x: screen.x + screen.w - size.w + 1, y, w: size.w, h: size.h };
  }
  if (edge === "left") {
    const y = clamp(along, screen.wy, screen.wy + screen.wh - size.h);
    return { x: screen.x - 1, y, w: size.w, h: size.h };
  }
  if (edge === "top") {
    const x = clamp(along, screen.wx, screen.wx + screen.ww - size.w);
    return { x, y: screen.wy, w: size.w, h: size.h };
  }
  if (edge === "bottom") {
    const x = clamp(along, screen.wx, screen.wx + screen.ww - size.w);
    return { x, y: screen.wy + screen.wh - size.h, w: size.w, h: size.h };
  }
  const x = clamp(along, screen.wx, screen.wx + screen.ww - size.w);
  return { x, y: screen.wy + 80, w: size.w, h: size.h };
}

