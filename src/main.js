function escapeHtml(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

const CHANGELOG_URL = "https://github.com/rayelzz/UsageBar-tauri/blob/main/CHANGELOG.md";

function safeHttpUrl(raw) {
  try {
    const url = new URL(String(raw || "").trim());
    if (url.protocol === "http:" || url.protocol === "https:") return url.href;
  } catch {
    /* ignore */
  }
  return "";
}

function notesLink(label, href) {
  const url = safeHttpUrl(href);
  if (!url) return escapeHtml(label);
  return `<a class="update-notes-link" href="${escapeHtml(url)}" data-open-url="${escapeHtml(url)}">${escapeHtml(label)}</a>`;
}

function inlineMd(s) {
  const src = String(s || "");
  const chunks = [];
  const re = /\[([^\]]+)\]\(([^)]+)\)/g;
  let last = 0;
  let m;
  while ((m = re.exec(src))) {
    chunks.push({ t: src.slice(last, m.index) });
    chunks.push({ a: m[1], href: m[2] });
    last = m.index + m[0].length;
  }
  chunks.push({ t: src.slice(last) });
  const html = chunks
    .map((c) => (c.a != null ? notesLink(c.a, c.href) : escapeHtml(c.t)))
    .join("")
    .replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>")
    .replace(/`([^`]+)`/g, "<code>$1</code>");
  if (html.includes("data-open-url")) return html;
  return html.replace(/CHANGELOG\.md/g, notesLink("CHANGELOG.md", CHANGELOG_URL));
}

function notesHtml(raw) {
  const parts = [];
  let list = [];
  const flushList = () => {
    if (!list.length) return;
    parts.push(`<ul class="update-notes-list">${list.map((item) => `<li>${item}</li>`).join("")}</ul>`);
    list = [];
  };
  for (const line of String(raw || "").split(/\n/)) {
    const trimmed = line.trim();
    if (!trimmed) {
      flushList();
      continue;
    }
    if (/^#{1,6}\s/.test(trimmed)) {
      flushList();
      continue;
    }
    const item = trimmed.match(/^[-*]\s+(.+)/);
    if (item) {
      list.push(inlineMd(item[1]));
      continue;
    }
    flushList();
    parts.push(`<p class="update-notes-p">${inlineMd(trimmed)}</p>`);
  }
  flushList();
  return parts.join("");
}

function paintUsageCard(payload) {
  const snap = payload.snap;
  const spec = ICONS[snap.id];
  if (!spec) return;
  const rule = spec.evenOdd ? 'fill-rule="evenodd"' : "";
  const soon = payload.mode === "creditSoon";
  const notice = !soon && (payload.resetNotice || snap.resetNotice);
  const creditNotice = payload.creditNotice || snap.creditNotice;
  const banner = soon
    ? `<div class="reset-banner"><div class="reset-title">${t().creditSoonTitle}</div></div>`
    : notice
      ? `<div class="reset-banner"><div class="reset-title">${t().resetTitle}</div></div>`
      : "";
  const close = soon
    ? `<button type="button" class="tip-close" data-close-credit="${snap.id}" aria-label="Close">×</button>`
    : notice
      ? `<button type="button" class="tip-close" data-close-reset="${snap.id}" aria-label="Close">×</button>`
      : "";
  const metricsHtml = soon
    ? ""
    : !snap.metrics?.length
      ? `<div class="empty${isQuerying(snap) ? " querying" : ""}">${localizeError(snap)}</div>`
      : snap.metrics
          .map((m, i) => {
            const shown = shownPct(m.percent) ?? 0;
            const color = usageColor(m.percent);
            return `<div class="metric">
            <div class="metric-top"><span>${localizeMetricLabel(m.label)}</span><span class="metric-reset">${payload.resets?.[i] || ""}</span></div>
            <div class="track"><div class="fill" style="width:${Math.min(Math.max(shown, 0), 100)}%;background:${color}"></div></div>
            <div class="used">${quotaText(m.percent)}</div>
          </div>`;
          })
          .join("");
  const soonItems = soon ? creditNotice?.items || [] : [];
  const credits = soon ? [] : resetCreditsOf(snap);
  const creditsHtml = soon
    ? `<div class="credit-block">
      ${soonItems
        .map(
          (c) => `<div class="credit-soon-item">
            <div class="credit-title">${localizeResetCreditTitle(c.title)}</div>
            <div class="credit-soon-meta">
              <span class="credit-left">${formatCreditRemaining(c.expiresAt)}</span>
              <span class="${creditExpClass(c.expiresAt).trim()}">${formatCreditExpiry(c.expiresAt)}</span>
            </div>
          </div>`
        )
        .join("")}
    </div>`
    : !credits.length
      ? ""
      : `<div class="credit-block">
      <div class="credit-head">${t().resetCards}<span class="credit-count">${t().resetCardCount(credits.length)}</span></div>
      ${credits
        .map(
          (c) => `<div class="credit-row">
            <span class="credit-title">${localizeResetCreditTitle(c.title)}</span>
            <span class="${creditExpClass(c.expiresAt).trim()}">${formatCreditExpiry(c.expiresAt)}</span>
          </div>`
        )
        .join("")}
    </div>`;
  const card = document.getElementById("tip-card");
  card.dataset.resetId = notice ? snap.id : "";
  card.dataset.creditId = soon ? snap.id : "";
  card.classList.remove("update-only", "update-notes", "menu-card", "tip-card-fade");
  card.innerHTML = `
    ${close}
    <div class="card-head">
      <svg class="mini glyph" viewBox="${spec.viewBox}">${spec.d.map((p) => `<path ${rule} d="${p}"/>`).join("")}</svg>
      <div class="title">${usageTitle(snap.id)}</div>
    </div>${banner}${metricsHtml}${creditsHtml}`;
  if (payload.fade) {
    void card.offsetWidth;
    card.classList.add("tip-card-fade");
  }
  const tip = document.getElementById("tip");
  tip.classList.remove("menu-tip", "update-only", "update-notes", "arrow-left", "arrow-right", "arrow-up", "arrow-down");
  tip.classList.add("tip", "arrow-" + (payload.arrow || "right"));
  tip.classList.toggle("hot", tipHot);
}

function paintTip(payload) {
  if (!payload?.show) {
    resetTipLayout();
    setWindowBlur("tip", 0);
    return;
  }
  prefs.locale = payload.locale === "zh" ? "zh" : "en";
  if (payload.displayValue) {
    prefs.displayValue = payload.displayValue === "remaining" ? "remaining" : "used";
  }
  if (payload.kind === "providers" && payload.state?.visibleProviders) {
    prefs.visibleProviders = normalizeVisible(payload.state.visibleProviders);
  }
  applyLocale();
  const ptr = document.getElementById("tip-pointer");
  if (payload.kind === "menu" || payload.kind === "providers") {
    clearTipSlide();
    const root = document.getElementById("tip-root");
    const tip = document.getElementById("tip");
    const card = document.getElementById("tip-card");
    root.classList.add("menu-backdrop");
    card.dataset.resetId = "";
    card.classList.remove("update-only", "update-notes");
    card.classList.add("menu-card");
    card.classList.toggle("providers-card", payload.kind === "providers");
    card.innerHTML =
      payload.kind === "providers" ? providersPanelHtml(payload.state) : menuPanelHtml(payload.state);
    tip.className = "tip menu-tip arrow-" + (payload.arrow || "right");
    if (payload.cardX != null && payload.cardY != null) {
      tip.style.left = `${payload.cardX}px`;
      tip.style.top = `${payload.cardY}px`;
      tip.style.width = `${payload.cardW || MENU_W}px`;
      tip.style.height = `${payload.cardH || 0}px`;
    }
    if (ptr) {
      ptr.hidden = true;
      ptr.style.marginTop = "";
      ptr.style.marginLeft = "";
      ptr.style.alignSelf = "";
    }
    paintOverlayChrome();
    requestAnimationFrame(() => syncMenuHover());
    return;
  }
  if (payload.slide) {
    document.getElementById("tip-root")?.classList.remove("menu-backdrop");
    if (ptr) ptr.hidden = true;
    applyTipSlide(payload.slide);
    paintUsageCard({ ...payload, fade: !!payload.slide.fade });
    paintOverlayChrome();
    emitTipReady();
    return;
  }
  resetTipLayout();
  if (ptr) ptr.hidden = true;
  if (!payload.snap) return;
  paintUsageCard(payload);
  paintOverlayChrome();
  emitTipReady();
}

function paintUpdateCard(payload) {
  if (!payload?.show) {
    resetTipLayout();
    setWindowBlur("update", 0);
    return;
  }
  prefs.locale = payload.locale === "zh" ? "zh" : "en";
  applyLocale();
  const ptr = document.getElementById("tip-pointer");
  if (ptr) ptr.hidden = true;
  const card = document.getElementById("tip-card");
  card.dataset.resetId = "";
  card.dataset.creditId = "";
  card.classList.remove("menu-card", "update-only", "tip-card-fade");
  card.classList.add("update-notes");
  const notes = notesHtml(payload.notes);
  card.innerHTML = `
    <button type="button" class="tip-close" data-close-update="1" aria-label="Close">×</button>
    <div class="card-head">
      <div class="title">${t().whatsNew}</div>
    </div>
    <div class="reset-banner"><div class="reset-title">${t().updateLine(payload.latest)}</div></div>
    ${notes ? `<div class="update-notes-body">${notes}</div>` : ""}
    <button type="button" class="update-install" data-open-release="1">${t().installVersion(payload.latest)}</button>`;
  document.getElementById("tip").className = "tip arrow-" + (payload.arrow || "right") + " hot";
  paintOverlayChrome();
  const box = document.getElementById("tip-card");
  const ch = box ? Math.ceil(box.scrollHeight || box.getBoundingClientRect().height) : 0;
  if (ch >= 2) {
    api()
      .event.emit("usagebar-update-ready", { h: ch })
      .catch(() => {});
    return;
  }
  requestAnimationFrame(() => {
    const card = document.getElementById("tip-card");
    const h = card ? Math.ceil(card.scrollHeight || card.getBoundingClientRect().height) : 0;
    api()
      .event.emit("usagebar-update-ready", { h })
      .catch(() => {});
  });
}

async function startUpdate() {
  document.documentElement.classList.add("update");
  document.getElementById("tip-root").hidden = false;
  document.getElementById("tip").className = "tip arrow-right";
  prefs = normalizeLoadedPrefs(await invoke("get_prefs"));
  applyOverlayLook();
  refreshWindowBlur();
  window.addEventListener("resize", () => pushOverlayFrost());
  await api().event.listen("usagebar-frost-sync", () => {
    pushOverlayFrost();
  });
  await api().event.listen("usagebar-prefs", (e) => {
    if (!e.payload) return;
    prefs = normalizeLoadedPrefs({ ...prefs, ...e.payload });
    applyLocale();
    applyOverlayLook();
  });
  await api().event.listen("usagebar-update-card", (e) => paintUpdateCard(e.payload));
  document.getElementById("tip-root").addEventListener("click", (e) => {
    const link = e.target.closest("[data-open-url]");
    if (link) {
      e.preventDefault();
      invoke("open_release_page", { url: link.dataset.openUrl }).catch(() => {});
      return;
    }
    if (e.target.closest("[data-close-update]")) {
      api().event.emit("usagebar-update-skip").catch(() => {});
      return;
    }
    if (e.target.closest("[data-open-release]")) {
      api().event.emit("usagebar-update-open").catch(() => {});
    }
  });
}

async function startTip() {
  document.getElementById("tip-root").hidden = false;
  document.getElementById("tip").className = "tip arrow-right";
  prefs = normalizeLoadedPrefs(await invoke("get_prefs"));
  applyOverlayLook();
  refreshWindowBlur();
  window.addEventListener("resize", () => pushOverlayFrost());
  await api().event.listen("usagebar-frost-sync", () => {
    pushOverlayFrost();
  });
  await api().event.listen("usagebar-tip", (e) => paintTip(e.payload));
  let updateHitRect = null;
  await api().event.listen("usagebar-update-hit", (e) => {
    updateHitRect = e.payload || null;
  });
  await api().event.listen("usagebar-tip-hover", (e) => {
    tipHot = !!e.payload;
    document.getElementById("tip")?.classList.toggle("hot", tipHot);
  });
  const tipRoot = document.getElementById("tip-root");
  let lookDragging = false;
  tipRoot.addEventListener("pointermove", syncMenuHover);
  tipRoot.addEventListener("pointerleave", () => {
    lastMenuPointer = null;
    setMenuHover(null);
  });
  tipRoot.addEventListener("pointerdown", (e) => {
    if (e.target.closest("[data-look-reset]")) e.stopPropagation();
    if (!e.target.closest("input[type=range][data-look]")) return;
    lookDragging = true;
    e.stopPropagation();
  });
  window.addEventListener("pointerup", () => {
    lookDragging = false;
  });
  window.addEventListener("pointercancel", () => {
    lookDragging = false;
  });
  const paintProvidersCard = () => {
    const card = document.getElementById("tip-card");
    if (!card?.classList.contains("providers-card")) return;
    card.innerHTML = providersPanelHtml({
      visibleProviders: normalizeVisible(prefs.visibleProviders),
    });
    paintOverlayChrome();
  };
  const saveVisibleProviders = (next) => {
    prefs.visibleProviders = normalizeVisible(next);
    invoke("set_visible_providers", { ids: prefs.visibleProviders })
      .then(() => paintProvidersCard())
      .catch((err) => console.error(err));
  };
  await api().event.listen("usagebar-prefs", (e) => {
    if (!e.payload) return;
    prefs = normalizeLoadedPrefs({ ...prefs, ...e.payload });
    applyLocale();
    applyOverlayLook();
    paintProvidersCard();
  });
  const applyLookSlider = (look, raw) => {
    if (look === "opacity") {
      prefs.barOpacity = raw / 100;
      const val = tipRoot.querySelector('[data-look-val="opacity"]');
      if (val) val.textContent = `${raw}%`;
    } else if (look === "blur") {
      prefs.barBlur = raw;
      const val = tipRoot.querySelector('[data-look-val="blur"]');
      if (val) val.textContent = String(raw);
    } else {
      return;
    }
    const range = tipRoot.querySelector(`input[data-look="${look}"]`);
    if (range) range.value = String(raw);
    const reset = tipRoot.querySelector(`[data-look-reset="${look}"]`);
    if (reset) reset.classList.toggle("is-default", raw === (look === "opacity" ? 100 : 0));
    applyOverlayLook();
    invoke("set_bar_look", {
      opacity: clampBarOpacity(prefs.barOpacity),
      blur: clampBarBlur(prefs.barBlur),
    }).catch((err) => console.error(err));
  };
  tipRoot.addEventListener("input", (e) => {
    const range = e.target.closest("input[type=range][data-look]");
    if (!range) return;
    e.stopPropagation();
    applyLookSlider(range.dataset.look, Number(range.value));
  });
  tipRoot.addEventListener("change", (e) => {
    const input = e.target.closest("input[data-toggle]");
    if (!input || !document.getElementById("tip-card")?.classList.contains("providers-card")) return;
    const id = input.dataset.toggle;
    let vis = normalizeVisible(prefs.visibleProviders);
    if (input.checked) {
      if (vis.includes(id)) return;
      if (vis.length >= SLOT_MAX) {
        input.checked = false;
        paintProvidersCard();
        return;
      }
      vis.push(id);
    } else {
      if (vis.length <= SLOT_MIN) {
        input.checked = true;
        paintProvidersCard();
        return;
      }
      vis = vis.filter((x) => x !== id);
    }
    saveVisibleProviders(vis);
  });
  tipRoot.addEventListener("click", (e) => {
    const move = e.target.closest("button[data-move]");
    if (move && !move.disabled && document.getElementById("tip-card")?.classList.contains("providers-card")) {
      e.preventDefault();
      e.stopPropagation();
      const id = move.dataset.move;
      const dir = Number(move.dataset.dir);
      const vis = normalizeVisible(prefs.visibleProviders);
      const i = vis.indexOf(id);
      const j = i + dir;
      if (i < 0 || j < 0 || j >= vis.length) return;
      [vis[i], vis[j]] = [vis[j], vis[i]];
      saveVisibleProviders(vis);
      return;
    }
    const reset = e.target.closest("[data-look-reset]");
    if (reset) {
      e.preventDefault();
      e.stopPropagation();
      const look = reset.dataset.lookReset;
      applyLookSlider(look, look === "opacity" ? 100 : 0);
      return;
    }
    const mid = e.target.closest("[data-mid]");
    if (mid) {
      if (MENU_TOGGLES.has(mid.dataset.mid)) {
        const check = mid.querySelector(".m-check");
        if (check) check.textContent = check.textContent.trim() ? "" : "✓";
      } else {
        paintChipSelection(mid);
      }
      api().event.emit("usagebar-menu", mid.dataset.mid).catch(() => {});
      return;
    }
    if (
      !lookDragging &&
      document.getElementById("tip")?.classList.contains("menu-tip") &&
      !e.target.closest(".menu-card")
    ) {
      if (
        updateHitRect &&
        e.clientX >= updateHitRect.x - 8 &&
        e.clientX <= updateHitRect.x + updateHitRect.w + 8 &&
        e.clientY >= updateHitRect.y - 8 &&
        e.clientY <= updateHitRect.y + updateHitRect.h + 8
      ) {
        return;
      }
      api().event.emit("usagebar-menu", "close").catch(() => {});
      return;
    }
    if (e.target.closest("[data-open-release]")) {
      api().event.emit("usagebar-update-open").catch(() => {});
      return;
    }
    const creditBtn = e.target.closest("[data-close-credit]");
    if (creditBtn) {
      api().event.emit("usagebar-credit-ack", creditBtn.dataset.closeCredit).catch(() => {});
      return;
    }
    const btn = e.target.closest("[data-close-reset]");
    if (!btn) return;
    api().event.emit("usagebar-reset-ack", btn.dataset.closeReset).catch(() => {});
  });
}

const kind = new URLSearchParams(location.search).get("w") || "bar";
if (kind === "tip") startTip().catch((err) => console.error(err));
else if (kind === "update") startUpdate().catch((err) => console.error(err));
else startBar().catch((err) => console.error(err));
