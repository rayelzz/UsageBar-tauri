function tipHeight(snap) {
  const n = Math.max(snap?.metrics?.length || 1, 1);
  let h = 54 + n * 52 + 8;
  if (snap?.resetNotice) {
    h += 36;
  }
  if (prefs.edge === "top" || prefs.edge === "bottom") {
    h += 12;
  }
  return Math.min(Math.max(h, 100), 360);
}

async function renderTip() {
  const snap = snaps.find((s) => s.id === hovered);
  const tipWin = await getWindow("tip");
  if (!snap || !tipWin) {
    await tipWin?.hide();
    return;
  }
  const resets = (snap.metrics || []).map((m) => formatReset(m.resetsAt));
  const locale = prefs.locale === "zh" ? "zh" : "en";
  const arrow =
    prefs.edge === "left"
      ? "left"
      : prefs.edge === "top"
        ? "up"
        : prefs.edge === "bottom"
          ? "down"
          : "right";
  await api().event.emit("usagebar-tip", {
    show: true,
    snap,
    resets,
    arrow,
    locale,
    resetNotice: snap.resetNotice || null,
  });
  const h = tipHeight(snap);
  try {
    await tipWin.setMinSize(new (LogicalSize())(1, 1));
  } catch {
    /* older runtime */
  }
  await tipWin.setSize(new (LogicalSize())(280, h));
}

async function resolveScreen(list, point) {
  if (prefs.screenName) {
    const named = list.find((s) => s.name === prefs.screenName);
    if (named) return named;
  }
  if (point) return monitorAt(point, list);
  try {
    const primary = await api().window.primaryMonitor();
    if (primary) return logicalMonitor(primary);
  } catch {
    /* fall through */
  }
  return list[0];
}

function inSystemBarBand(point, screen) {
  const topBand = screen.wy - screen.y;
  if (
    topBand > 8 &&
    point.y >= screen.y - 2 &&
    point.y <= screen.wy + 4 &&
    point.x >= screen.x &&
    point.x <= screen.x + screen.w
  ) {
    return true;
  }
  const bottomBand = screen.y + screen.h - (screen.wy + screen.wh);
  if (
    bottomBand > 8 &&
    point.y >= screen.wy + screen.wh - 4 &&
    point.y <= screen.y + screen.h + 2 &&
    point.x >= screen.x &&
    point.x <= screen.x + screen.w
  ) {
    return true;
  }
  return false;
}

async function placeWindows() {
  const bar = getCurrentWindow();
  try {
    await bar.setMinSize(new (LogicalSize())(1, 1));
  } catch {
    /* older runtime */
  }
  const frame = await invoke("place_bar");
  if (!frame) return;
  await layoutTip(frame, { w: frame.w, h: frame.h });
}

async function layoutTip(frame, size) {
  const snap = snaps.find((s) => s.id === hovered);
  const tipWin = await getWindow("tip");
  if (!snap || !tipWin) return;
  const idx = Math.max(0, snaps.findIndex((s) => s.id === hovered));
  const count = Math.max(snaps.length, 1);
  const th = tipHeight(snap);
  const tw = 280;
  const pad = isIcons() ? { t: 5, b: 5, l: 5, r: 5 } : padding(prefs.edge);
  const start = isVertical(prefs.edge) ? pad.t : pad.l;
  const end = isVertical(prefs.edge) ? pad.b : pad.r;
  const along = isVertical(prefs.edge) ? frame.h : frame.w;
  const inner = Math.max(along - start - end, 1);
  const slot = inner / count;
  const mid = start + (idx + 0.5) * slot;
  let x = 0;
  let y = 0;
  if (prefs.edge === "right" || prefs.edge === "floating") {
    x = frame.x - tw - 6;
    y = frame.y + mid - th / 2;
  } else if (prefs.edge === "left") {
    x = frame.x + frame.w + 6;
    y = frame.y + mid - th / 2;
  } else if (prefs.edge === "top") {
    x = frame.x + mid - tw / 2;
    y = frame.y + frame.h + 6;
  } else {
    x = frame.x + mid - tw / 2;
    y = frame.y - th - 6;
  }
  await tipWin.setPosition(new (LogicalPosition())(x, y));
  await tipWin.show();
}

function paintHover() {
  document.querySelectorAll("[data-id]").forEach((el) => {
    el.classList.toggle("hovered", el.dataset.id === hovered);
  });
}

async function setTipClickable(on) {
  const tipWin = await getWindow("tip");
  try {
    await tipWin?.setIgnoreCursorEvents(!on);
  } catch {
    /* older runtime */
  }
}

async function acknowledgeReset(id) {
  const snap = snaps.find((s) => s.id === id);
  if (!id || !snap?.resetNotice) return;
  await invoke("dismiss_reset_notice", { id });
  snaps = snaps.map((s) => (s.id === id ? { ...s, resetNotice: null } : s));
  if (resetToastId === id) resetToastId = null;
  await setTipClickable(false);
  renderBar();
}

function nextResetSnap() {
  return snaps.find((s) => s.resetNotice?.fresh) || snaps.find((s) => s.resetNotice) || null;
}

async function maybeShowResetToast() {
  if (resetToastId || menuOpen || dragging) return false;
  const next = nextResetSnap();
  if (!next) return false;
  await showResetToast(next);
  return true;
}

async function closeResetToast(id) {
  const target = id || resetToastId;
  if (!target) return;
  await acknowledgeReset(target);
  hovered = null;
  paintHover();
  if (await maybeShowResetToast()) return;
  const tipWin = await getWindow("tip");
  await api().event.emit("usagebar-tip", { show: false });
  await tipWin?.hide();
}

async function showResetToast(snap) {
  if (!snap?.id || menuOpen || dragging) return;
  resetToastId = snap.id;
  hovered = snap.id;
  paintHover();
  await setTipClickable(true);
  await renderTip();
  const pos = await getCurrentWindow().outerPosition();
  const size = await getCurrentWindow().outerSize();
  const scale = await getCurrentWindow().scaleFactor();
  await layoutTip(
    { x: pos.x / scale, y: pos.y / scale, w: size.width / scale, h: size.height / scale },
    barSize(prefs.edge)
  );
}

async function setHovered(id) {
  if (resetToastId) return;
  if (hovered === id) return;
  hovered = id;
  paintHover();
  if (!id) {
    const tipWin = await getWindow("tip");
    await api().event.emit("usagebar-tip", { show: false });
    await tipWin?.hide();
    return;
  }
  await renderTip();
  const pos = await getCurrentWindow().outerPosition();
  const size = await getCurrentWindow().outerSize();
  const scale = await getCurrentWindow().scaleFactor();
  await layoutTip(
    { x: pos.x / scale, y: pos.y / scale, w: size.width / scale, h: size.height / scale },
    barSize(prefs.edge)
  );
}

async function savePrefs() {
  await invoke("set_prefs", { prefs });
}

async function refresh() {
  const got = await invoke("fetch_usage");
  snaps = slotsFrom(got);
  if (hovered && !snaps.some((s) => s.id === hovered)) {
    await setHovered(null);
  }
  renderBar();
  if (resetToastId) {
    const current = snaps.find((s) => s.id === resetToastId);
    if (current?.resetNotice) {
      hovered = resetToastId;
      await renderTip();
      return;
    }
    resetToastId = null;
  }
  if (await maybeShowResetToast()) return;
  if (hovered) await renderTip();
}

function restartTimer() {
  if (refreshTimer) clearInterval(refreshTimer);
  refreshTimer = null;
  if (prefs.refreshInterval > 0) {
    refreshTimer = setInterval(refresh, prefs.refreshInterval * 1000);
  }
}

async function setLocale(next) {
  const locale = next === "zh" ? "zh" : "en";
  if (prefs.locale === locale) return;
  prefs.locale = locale;
  applyLocale();
  await savePrefs();
  if (hovered) await renderTip();
}

async function setDisplayStyle(style) {
  if (prefs.displayStyle === style) return;
  await setHovered(null);
  prefs.displayStyle = style;
  await savePrefs();
  renderBar();
  await placeWindows();
  hideMenu();
}

async function snapTo(edge) {
  prefs.edge = edge;
  const pos = await getCurrentWindow().outerPosition();
  const size = barSize(edge);
  const scale = await getCurrentWindow().scaleFactor();
  const frame = { x: pos.x / scale, y: pos.y / scale, w: size.w, h: size.h };
  const list = await monitors();
  const screen = await monitorAt({ x: frame.x + frame.w / 2, y: frame.y + frame.h / 2 }, list);
  prefs.screenName = screen.name;
  prefs.along = isVertical(edge) ? frame.y : frame.x;
  if (edge === "floating") {
    prefs.floatingX = frame.x;
    prefs.floatingY = frame.y;
  }
  await savePrefs();
  renderBar();
  await placeWindows();
  hideMenu();
}

function hideMenu() {
  menuOpen = false;
  document.getElementById("menu").hidden = true;
}

async function onNativeMenu(id) {
  menuOpen = false;
  if (id === "lock") {
    prefs.locked = !prefs.locked;
    await savePrefs();
  } else if (id === "click") {
    prefs.clickThrough = !prefs.clickThrough;
    await savePrefs();
  } else if (id.startsWith("snap:")) {
    await snapTo(id.slice(5));
    return;
  } else if (id === "refresh") {
    await refresh();
  } else if (id.startsWith("interval:")) {
    prefs.refreshInterval = Number(id.slice(9));
    await savePrefs();
    restartTimer();
  } else if (id.startsWith("style:")) {
    await setDisplayStyle(id.slice(6));
    return;
  } else if (id.startsWith("locale:")) {
    await setLocale(id.slice(7));
    return;
  } else if (id === "login") {
    const auto = api().autostart;
    if (auto) {
      const on = await auto.isEnabled();
      if (on) await auto.disable();
      else await auto.enable();
      prefs.launchAtLogin = await auto.isEnabled();
    } else {
      prefs.launchAtLogin = !prefs.launchAtLogin;
    }
    await savePrefs();
  } else if (id === "tools") {
    await invoke("open_settings");
    return;
  } else if (id === "quit") {
    await invoke("quit");
    return;
  }
}

async function showNativeMenu() {
  const { Menu, MenuItem, CheckMenuItem, PredefinedMenuItem, Submenu } = api().menu;
  const run = (id) => () => {
    onNativeMenu(id).catch((err) => console.error(err));
  };
  const item = (id, text) => MenuItem.new({ id, text, action: run(id) });
  const check = (id, text, checked) =>
    CheckMenuItem.new({ id, text, checked, action: run(id) });
  const ui = t();
  const refreshItems = await Promise.all(
    REFRESH_SECS.map((sec) =>
      check(`interval:${sec}`, intervalLabel(sec), prefs.refreshInterval === sec)
    )
  );
  const styleItems = await Promise.all([
    check("style:full", ui.ringUsage, !isIcons()),
    check("style:icons", ui.transparentIcons, isIcons()),
  ]);
  const langItems = await Promise.all([
    check("locale:en", "English", !isZh()),
    check("locale:zh", "中文", isZh()),
  ]);
  const items = await Promise.all([
    item("refresh", ui.refreshNow),
    Submenu.new({ text: ui.autoRefresh, items: refreshItems }),
    PredefinedMenuItem.new({ item: "Separator" }),
    item("lock", prefs.locked ? ui.unlock : ui.lock),
    check("click", ui.clickThrough, !!prefs.clickThrough),
    PredefinedMenuItem.new({ item: "Separator" }),
    check("snap:left", ui.snapLeft, prefs.edge === "left"),
    check("snap:right", ui.snapRight, prefs.edge === "right"),
    check("snap:top", ui.snapTop, prefs.edge === "top"),
    check("snap:bottom", ui.snapBottom, prefs.edge === "bottom"),
    Submenu.new({ text: ui.displayStyle, items: styleItems }),
    Submenu.new({ text: ui.language, items: langItems }),
    item("tools", ui.tools),
    PredefinedMenuItem.new({ item: "Separator" }),
    check("login", ui.openAtLogin, !!prefs.launchAtLogin),
    PredefinedMenuItem.new({ item: "Separator" }),
    item("quit", ui.quit),
  ]);
  const menu = await Menu.new({ items });
  menuOpen = true;
  await invoke("set_menu_open", { open: true });
  await setHovered(null);
  await menu.popup();
  menuOpen = false;
  await invoke("set_menu_open", { open: false });
}

async function applyLayout(payload) {
  if (!payload) return;
  const edgeChanged = payload.edge && payload.edge !== prefs.edge;
  if (payload.edge) prefs.edge = payload.edge;
  if (typeof payload.along === "number") prefs.along = payload.along;
  if (typeof payload.floatingX === "number") prefs.floatingX = payload.floatingX;
  if (typeof payload.floatingY === "number") prefs.floatingY = payload.floatingY;
  if (typeof payload.screenName === "string") prefs.screenName = payload.screenName;
  dragging = !!payload.dragging;
  document.documentElement.classList.toggle("dragging", dragging);
  if (dragging) await setHovered(null);
  if (edgeChanged) {
    renderBar();
    if (!dragging) await placeWindows();
  }
}

async function startBar() {
  document.getElementById("bar-root").hidden = false;
  osName = await invoke("os_name");
  prefs = await invoke("get_prefs");
  if (prefs.displayStyle !== "icons") prefs.displayStyle = "full";
  prefs.locale = prefs.locale === "zh" ? "zh" : "en";
  prefs.visibleProviders = normalizeVisible(prefs.visibleProviders);
  snaps = slotsFrom([]);
  applyLocale();
  try {
    if (api().autostart) {
      prefs.launchAtLogin = await api().autostart.isEnabled();
    }
  } catch {
    /* plugin optional */
  }
  renderBar();
  await placeWindows();
  refresh().catch((err) => console.error(err));
  restartTimer();
  document.addEventListener("contextmenu", (e) => {
    e.preventDefault();
    showNativeMenu().catch((err) => console.error(err));
  });
  document.addEventListener("pointerdown", (e) => {
    if (e.button === 0) invoke("set_pointer", { left: true }).catch(() => {});
  });
  document.addEventListener("pointerup", (e) => {
    if (e.button === 0) invoke("set_pointer", { left: false }).catch(() => {});
  });
  document.addEventListener("pointercancel", () => {
    invoke("set_pointer", { left: false }).catch(() => {});
  });
  await api().event.listen("usagebar-menu", (e) => {
    onNativeMenu(e.payload).catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-layout", (e) => {
    applyLayout(e.payload).catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-prefs", (e) => {
    if (!e.payload) return;
    const prev = (prefs.visibleProviders || []).join(",");
    prefs = { ...prefs, ...e.payload };
    if (prefs.displayStyle !== "icons") prefs.displayStyle = "full";
    prefs.locale = prefs.locale === "zh" ? "zh" : "en";
    prefs.visibleProviders = normalizeVisible(prefs.visibleProviders);
    applyLocale();
    if (prev !== prefs.visibleProviders.join(",")) {
      snaps = slotsFrom(snaps.filter((s) => s.id));
      renderBar();
      placeWindows().catch((err) => console.error(err));
      refresh().catch((err) => console.error(err));
    }
  });
  await api().event.listen("usagebar-hover", (e) => {
    if (menuOpen || dragging) {
      if (hovered) setHovered(null).catch((err) => console.error(err));
      return;
    }
    if (resetToastId) return;
    setHovered(e.payload || null).catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-reset-ack", (e) => {
    closeResetToast(e.payload).catch((err) => console.error(err));
  });
}

function paintTip(payload) {
  if (!payload?.show || !payload.snap) return;
  prefs.locale = payload.locale === "zh" ? "zh" : "en";
  applyLocale();
  const snap = payload.snap;
  const spec = ICONS[snap.id];
  if (!spec) return;
  const rule = spec.evenOdd ? 'fill-rule="evenodd"' : "";
  const metricsHtml = !snap.metrics?.length
    ? `<div class="empty">${localizeError(snap)}</div>`
    : snap.metrics
        .map((m, i) => {
          const color = usageColor(m.percent);
          return `<div class="metric">
            <div class="metric-top"><span>${localizeMetricLabel(m.label)}</span><span class="metric-reset">${payload.resets?.[i] || ""}</span></div>
            <div class="track"><div class="fill" style="width:${Math.min(Math.max(m.percent, 0), 100)}%;background:${color}"></div></div>
            <div class="used">${usedText(m.percent)}</div>
          </div>`;
        })
        .join("");
  const notice = payload.resetNotice || snap.resetNotice;
  const banner = notice
    ? `<div class="reset-banner"><div class="reset-title">${t().resetTitle}</div></div>`
    : "";
  const close = notice
    ? `<button type="button" class="tip-close" data-close-reset="${snap.id}" aria-label="Close">×</button>`
    : "";
  const card = document.getElementById("tip-card");
  card.dataset.resetId = notice ? snap.id : "";
  card.innerHTML = `
    ${close}
    <div class="card-head">
      <svg class="mini glyph" viewBox="${spec.viewBox}">${spec.d.map((p) => `<path ${rule} d="${p}"/>`).join("")}</svg>
      <div class="title">${usageTitle(snap.id)}</div>
    </div>${banner}${metricsHtml}`;
  document.getElementById("tip").className =
    "tip arrow-" + (payload.arrow || "right") + (tipHot ? " hot" : "");
}

async function startTip() {
  document.getElementById("tip-root").hidden = false;
  document.getElementById("tip").className = "tip arrow-right";
  await api().event.listen("usagebar-tip", (e) => paintTip(e.payload));
  await api().event.listen("usagebar-tip-hover", (e) => {
    tipHot = !!e.payload;
    document.getElementById("tip")?.classList.toggle("hot", tipHot);
  });
  document.getElementById("tip-root").addEventListener("click", (e) => {
    const btn = e.target.closest("[data-close-reset]");
    if (!btn) return;
    api().event.emit("usagebar-reset-ack", btn.dataset.closeReset).catch(() => {});
  });
}

function renderSettings() {
  const ui = t();
  const vis = normalizeVisible(prefs.visibleProviders);
  const selected = new Set(vis);
  document.getElementById("settings-title").textContent = ui.toolsTitle;
  document.getElementById("settings-hint").textContent = ui.toolsHint;
  const count = document.getElementById("settings-count");
  count.textContent =
    vis.length >= SLOT_MAX ? ui.toolsMax : vis.length <= SLOT_MIN ? ui.toolsMin : ui.selectedCount(vis.length);
  count.classList.toggle("warn", vis.length >= SLOT_MAX || vis.length <= SLOT_MIN);
  const rest = CATALOG_IDS.filter((id) => !selected.has(id));
  const rows = [...vis, ...rest]
    .map((id) => {
      const on = selected.has(id);
      const idx = vis.indexOf(id);
      const upOff = !on || idx <= 0;
      const downOff = !on || idx < 0 || idx >= vis.length - 1;
      const spec = ICONS[id];
      const rule = spec?.evenOdd ? 'fill-rule="evenodd"' : "";
      const icon = spec
        ? `<span class="icon"><svg class="glyph" viewBox="${spec.viewBox}">${spec.d
            .map((p) => `<path ${rule} d="${p}"/>`)
            .join("")}</svg></span>`
        : "";
      return `<div class="settings-row" data-id="${id}">
        <label>
          <input type="checkbox" data-toggle="${id}" ${on ? "checked" : ""} ${
            !on && vis.length >= SLOT_MAX ? "disabled" : ""
          }/>
          ${icon}
          <span class="name">${vendorName(id)}</span>
        </label>
        <button type="button" data-move="${id}" data-dir="-1" ${upOff ? "disabled" : ""} title="${ui.moveUp}">↑</button>
        <button type="button" data-move="${id}" data-dir="1" ${downOff ? "disabled" : ""} title="${ui.moveDown}">↓</button>
      </div>`;
    })
    .join("");
  document.getElementById("settings-list").innerHTML = rows;
}

async function saveVisible(next) {
  prefs.visibleProviders = normalizeVisible(next);
  await savePrefs();
  renderSettings();
}

async function startSettings() {
  document.documentElement.classList.add("settings");
  document.getElementById("settings-root").hidden = false;
  prefs = await invoke("get_prefs");
  prefs.locale = prefs.locale === "zh" ? "zh" : "en";
  prefs.visibleProviders = normalizeVisible(prefs.visibleProviders);
  applyLocale();
  renderSettings();
  const root = document.getElementById("settings-root");
  root.addEventListener("change", (e) => {
    const input = e.target.closest("input[data-toggle]");
    if (!input) return;
    const id = input.dataset.toggle;
    let vis = normalizeVisible(prefs.visibleProviders);
    if (input.checked) {
      if (vis.includes(id)) return;
      if (vis.length >= SLOT_MAX) {
        input.checked = false;
        renderSettings();
        return;
      }
      vis.push(id);
    } else {
      if (vis.length <= SLOT_MIN) {
        input.checked = true;
        renderSettings();
        return;
      }
      vis = vis.filter((x) => x !== id);
    }
    saveVisible(vis).catch((err) => console.error(err));
  });
  root.addEventListener("click", (e) => {
    const btn = e.target.closest("button[data-move]");
    if (!btn || btn.disabled) return;
    const id = btn.dataset.move;
    const dir = Number(btn.dataset.dir);
    const vis = normalizeVisible(prefs.visibleProviders);
    const i = vis.indexOf(id);
    const j = i + dir;
    if (i < 0 || j < 0 || j >= vis.length) return;
    [vis[i], vis[j]] = [vis[j], vis[i]];
    saveVisible(vis).catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-prefs", (e) => {
    if (!e.payload) return;
    prefs = { ...prefs, ...e.payload };
    prefs.locale = prefs.locale === "zh" ? "zh" : "en";
    prefs.visibleProviders = normalizeVisible(prefs.visibleProviders);
    applyLocale();
    renderSettings();
  });
}

const kind = new URLSearchParams(location.search).get("w") || "bar";
if (kind === "tip") startTip().catch((err) => console.error(err));
else if (kind === "settings") startSettings().catch((err) => console.error(err));
else startBar().catch((err) => console.error(err));
