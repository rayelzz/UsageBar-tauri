async function finishRefreshPaint() {
  if (hovered && !snaps.some((s) => s.id === hovered)) {
    await setHovered(null);
  }
  renderBar();
  if (resetToastId) {
    const current = snaps.find((s) => s.id === resetToastId);
    if (current?.resetNotice) {
      hovered = resetToastId;
      await renderTip();
      return;
    }
    resetToastId = null;
  }
  if (await maybeShowResetToast()) return;
  if (hovered) await renderTip();
  else await showUpdateToast();
}

async function refresh() {
  if (refreshing) {
    refreshQueued = true;
    return;
  }
  refreshing = true;
  try {
    do {
      refreshQueued = false;
      const gen = ++refreshGen;
      snaps = snaps.map((s) => (hasMetrics(s) ? s : { ...s, loading: true }));
      renderBar();
      if (hovered) await renderTip();
      let got = null;
      try {
        got = await invoke("fetch_usage");
      } catch (err) {
        console.error(err);
        if (gen !== refreshGen) continue;
        snaps = snaps.map((s) =>
          hasMetrics(s) ? { ...s, loading: false } : { ...s, loading: false, error: s.error || "api_error" }
        );
      }
      if (gen !== refreshGen) continue;
      if (Array.isArray(got)) {
        snaps = slotsFrom(got).map((s) => ({ ...s, loading: false }));
      }
      await finishRefreshPaint();
    } while (refreshQueued);
  } finally {
    refreshing = false;
  }
}

function restartTimer() {
  if (refreshTimer) clearInterval(refreshTimer);
  refreshTimer = null;
  if (prefs.refreshInterval > 0) {
    refreshTimer = setInterval(refresh, prefs.refreshInterval * 1000);
  }
}

