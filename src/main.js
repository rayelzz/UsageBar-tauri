function menuPanelHtml(st) {
  return menuSpec(st)
    .map((r) => {
      if (r.k === "sep") return `<div class="m-sep"></div>`;
      if (r.k === "label") return `<div class="m-label">${r.label}</div>`;
      if (r.k === "info") return `<div class="m-info">${r.label}</div>`;
      if (r.k === "chips") {
        return `<div class="m-chips">${r.ids
          .map(
            (id, i) =>
              `<button type="button" class="m-chip${r.on[i] ? " on" : ""}" data-mid="${id}">${r.labels[i]}</button>`
          )
          .join("")}</div>`;
      }
      const extra =
        (r.extraKind === "link" || r.extraKind === "install") && r.extra
          ? `<span class="m-extra link" data-mid="${r.extraId || "latest"}">${r.extra}${
              r.extraKind === "link" ? JUMP_ICON : ""
            }</span>`
          : r.extra
            ? `<span class="m-extra muted">${r.extra}</span>`
            : "";
      return `<button type="button" class="m-row${r.cls ? " " + r.cls : ""}" data-mid="${r.id}"><span class="m-check">${
        r.check ? "✓" : ""
      }</span><span class="m-grow">${r.label}</span>${extra}</button>`;
    })
    .join("");
}

function menuPanelHeight(st) {
  const H = { row: 30, sep: 11, label: 20, chips: 30, info: 22 };
  return menuSpec(st).reduce((sum, r) => sum + (H[r.k] || 0), 0) + 16;
}

