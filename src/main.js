function radii(w, h, along) {
  const base = Math.min(w, h);
  let fillet = base * 0.35;
  let corner = base * 0.42;
  const limit = along / 2;
  const total = fillet + corner;
  if (total > limit && total > 0) {
    const s = limit / total;
    fillet *= s;
    corner *= s;
  }
  return [fillet, corner];
}

