function nearest(frame, screen) {
  const right = Math.abs(frame.x + frame.w - (screen.x + screen.w));
  const left = Math.abs(frame.x - screen.x);
  const top = Math.abs(frame.y - screen.wy);
  const bottom = Math.abs(frame.y + frame.h - (screen.wy + screen.wh));
  const pairs = [
    ["right", right],
    ["left", left],
    ["top", top],
    ["bottom", bottom],
  ];
  pairs.sort((a, b) => a[1] - b[1]);
  return pairs[0][1] <= SNAP ? pairs[0][0] : "floating";
}

