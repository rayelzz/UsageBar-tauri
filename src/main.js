const MENU_TOGGLES = new Set(["lock", "click", "login", "autoupdate"]);

async function onNativeMenu(id) {
  if (id === "lock") {
    prefs.locked = !prefs.locked;
    await savePrefs();
  } else if (id === "click") {
    prefs.clickThrough = !prefs.clickThrough;
    await savePrefs();
  } else if (id.startsWith("snap:")) {
    await snapTo(id.slice(5));
    return;
  } else if (id === "refresh") {
    await refresh();
  } else if (id.startsWith("interval:")) {
    prefs.refreshInterval = Number(id.slice(9));
    savePrefs().catch((err) => console.error(err));
    restartTimer();
  } else if (id.startsWith("style:")) {
    await setDisplayStyle(id.slice(6));
    return;
  } else if (id.startsWith("value:")) {
    await setDisplayValue(id.slice(6));
    return;
  } else if (id.startsWith("locale:")) {
    await setLocale(id.slice(7));
    return;
  } else if (id === "login") {
    prefs.launchAtLogin = !prefs.launchAtLogin;
    savePrefs().catch((err) => console.error(err));
    applyLaunchAtLogin(prefs.launchAtLogin).catch((err) => console.error(err));
  } else if (id === "autoupdate") {
    prefs.autoCheckUpdate = !prefs.autoCheckUpdate;
    savePrefs().catch((err) => console.error(err));
    applyAutoUpdatePref();
  } else if (id === "tools") {
    await invoke("open_settings");
    return;
  } else if (id === "quit") {
    await invoke("quit");
    return;
  }
}

