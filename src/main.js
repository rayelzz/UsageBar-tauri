async function handleMenuAction(id) {
  if (!id) return;
  if (id === "close") {
    await closeMenuPanel();
    return;
  }
  if (id === "checkupdate") {
    if (menuInstalling) return;
    await checkUpdateManual({ showNotes: true });
    return;
  }
  if (id === "update" || id === "latest") {
    await installAvailableUpdate();
    return;
  }
  if (id === "refresh") {
    await closeMenuPanel();
    refresh().catch((err) => console.error(err));
    return;
  }
  if (id === "menu-back") {
    await showPanelMenu(true);
    return;
  }
  if (id === "tools") {
    await showProvidersPanel(true);
    return;
  }
  if (id === "quit") {
    await closeMenuPanel();
    await onNativeMenu(id);
    return;
  }
  if (id.startsWith("snap:")) {
    await onNativeMenu(id);
    if (menuOpen) await showPanelMenu(true);
    return;
  }
  if (MENU_TOGGLES.has(id)) {
    await onNativeMenu(id);
    if (menuOpen) await showPanelMenu(false);
    return;
  }
  if (id.startsWith("interval:")) {
    prefs.refreshInterval = Number(id.slice(9));
    restartTimer();
    savePrefs().catch((err) => console.error(err));
    return;
  }
  if (id.startsWith("value:")) {
    setDisplayValue(id.slice(6));
    return;
  }
  if (id.startsWith("locale:")) {
    await setLocale(id.slice(7));
    if (menuOpen) await showPanelMenu(false);
    return;
  }
  await onNativeMenu(id);
  if (menuOpen) await showPanelMenu(false);
}

async function parkStickyTips() {
  clearCreditToastTimer();
  await hideUsageTip();
  await setTipClickable(false);
  if (updateToastOpen) {
    const win = await getWindow("update");
    await win?.hide();
  }
}

async function restoreStickyTips() {
  if (resetToastId) {
    const snap = snaps.find((s) => s.id === resetToastId);
    if (snap?.resetNotice) {
      hovered = resetToastId;
      paintHover();
      await setTipClickable(true);
      await renderTip();
      const frame = await currentBarFrame();
      await layoutTip(frame, barSize(prefs.edge));
      return;
    }
    resetToastId = null;
  }
  if (creditToastId) {
    const snap = snaps.find((s) => s.id === creditToastId);
    if (snap?.creditNotice) {
      await showCreditToast(snap);
      return;
    }
    clearCreditToastTimer();
    creditToastId = null;
  }
  if (updateToastOpen) await layoutUpdateCard();
}

async function applyLayout(payload) {
  if (!payload) return;
  const edgeChanged = payload.edge && payload.edge !== prefs.edge;
  if (payload.edge) prefs.edge = payload.edge;
  if (typeof payload.along === "number") prefs.along = payload.along;
  if (typeof payload.floatingX === "number") prefs.floatingX = payload.floatingX;
  if (typeof payload.floatingY === "number") prefs.floatingY = payload.floatingY;
  if (typeof payload.screenName === "string") prefs.screenName = payload.screenName;
  if (typeof payload.lastX === "number") prefs.lastX = payload.lastX;
  if (typeof payload.lastY === "number") prefs.lastY = payload.lastY;
  const nextDrag = !!payload.dragging;
  const ended = dragging && !nextDrag;
  dragging = nextDrag;
  document.documentElement.classList.toggle("dragging", dragging);
  if (dragging) {
    await parkStickyTips();
    if (!resetToastId && !creditToastId) await setHovered(null);
  }
  setBarHot();
  if (edgeChanged) {
    renderBar();
    if (!dragging) await placeWindows();
  } else if (ended) {
    await restoreStickyTips();
  }
}

async function startBar() {
  document.getElementById("bar-root").hidden = false;
  osName = await invoke("os_name");
  prefs = normalizeLoadedPrefs(await invoke("get_prefs"));
  prefsReady = true;
  snaps = slotsFrom([], true);
  try {
    appVersion = await invoke("app_version");
  } catch {
    appVersion = "";
  }
  applyLocale();
  applyBarLook();
  refreshWindowBlur();
  try {
    if (api().autostart) {
      prefs.launchAtLogin = await api().autostart.isEnabled();
    }
  } catch {
    /* plugin optional */
  }
  renderBar();
  await placeWindows();
  refresh().catch((err) => console.error(err));
  restartTimer();
  applyAutoUpdatePref();
  document.getElementById("gear-btn").addEventListener("pointerdown", (e) => {
    e.stopPropagation();
  });
  document.getElementById("gear-btn").addEventListener("click", (e) => {
    e.preventDefault();
    e.stopPropagation();
    if (menuOpen) closeMenuPanel().catch((err) => console.error(err));
    else showPanelMenu().catch((err) => console.error(err));
  });
  document.addEventListener("contextmenu", (e) => {
    e.preventDefault();
    if (!menuOpen) showPanelMenu().catch((err) => console.error(err));
  });
  document.addEventListener("pointerdown", (e) => {
    if (e.button === 0) invoke("set_pointer", { left: true }).catch(() => {});
  });
  document.addEventListener("pointerup", (e) => {
    if (e.button === 0) invoke("set_pointer", { left: false }).catch(() => {});
  });
  document.addEventListener("pointercancel", () => {
    invoke("set_pointer", { left: false }).catch(() => {});
  });
  await api().event.listen("usagebar-menu", (e) => {
    handleMenuAction(e.payload).catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-layout", (e) => {
    applyLayout(e.payload).catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-prefs", (e) => {
    if (!e.payload) return;
    const prev = (prefs.visibleProviders || []).join(",");
    const prevAuto = !!prefs.autoCheckUpdate;
    const prevValue = prefs.displayValue;
    const prevBlurOn = clampBarBlur(prefs.barBlur) > 0;
    prefs = normalizeLoadedPrefs({ ...prefs, ...e.payload });
    applyLocale();
    applyBarLook();
    if (prevAuto !== prefs.autoCheckUpdate) applyAutoUpdatePref();
    if (prev !== prefs.visibleProviders.join(",")) {
      snaps = slotsFrom(snaps.filter((s) => s.id), true);
      renderBar();
      placeWindows().catch((err) => console.error(err));
      refresh().catch((err) => console.error(err));
    } else if (prevValue !== prefs.displayValue) {
      paintShownPercents();
      if (hovered) renderTip().catch((err) => console.error(err));
    } else if (hovered && prevBlurOn !== clampBarBlur(prefs.barBlur) > 0) {
      tipStageFrame = null;
      currentBarFrame()
        .then((frame) => showUsageTip(frame))
        .catch((err) => console.error(err));
    }
  });
  await api().event.listen("usagebar-over", (e) => {
    setBarHot(!!e.payload);
  });
  await api().event.listen("usagebar-tip-ready", (e) => resolveTipReady(e.payload));
  await api().event.listen("usagebar-update-ready", (e) => resolveUpdateReady(e.payload));
  await api().event.listen("usagebar-hover", (e) => {
    if (menuOpen || dragging) {
      if (hovered) setHovered(null).catch((err) => console.error(err));
      return;
    }
    if (resetToastId) return;
    const id = e.payload || null;
    if (updateToastOpen && !id) return;
    if (creditToastId) {
      if (!id) return;
      acknowledgeCredit(creditToastId)
        .then(() => setHovered(id))
        .catch((err) => console.error(err));
      return;
    }
    setHovered(id).catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-reset-ack", (e) => {
    closeResetToast(e.payload).catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-credit-ack", (e) => {
    closeCreditToast(e.payload).catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-update-open", () => {
    openUpdateFromPrompt().catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-update-skip", () => {
    skipPromptedVersion().catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-update-progress", (e) => {
    const total = Number(e.payload?.total);
    const downloaded = Number(e.payload?.downloaded);
    if (!total || !Number.isFinite(downloaded)) return;
    const pct = Math.min(100, Math.round((downloaded / total) * 100));
    if (pct === menuInstallPercent) return;
    menuInstallPercent = pct;
    if (menuOpen) refreshMenuIfOpen(false).catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-usage", (e) => {
    if (e.payload) applyIncomingSnap(e.payload);
  });
}

