function paintTip(payload) {
  if (!payload?.show) {
    resetTipLayout();
    return;
  }
  prefs.locale = payload.locale === "zh" ? "zh" : "en";
  applyLocale();
  const ptr = document.getElementById("tip-pointer");
  if (payload.kind === "menu") {
    const root = document.getElementById("tip-root");
    const tip = document.getElementById("tip");
    const card = document.getElementById("tip-card");
    root.classList.add("menu-backdrop");
    card.dataset.resetId = "";
    card.classList.add("menu-card");
    card.innerHTML = menuPanelHtml(payload.state);
    tip.className = "tip menu-tip arrow-" + (payload.arrow || "right");
    if (payload.cardX != null && payload.cardY != null) {
      tip.style.left = `${payload.cardX}px`;
      tip.style.top = `${payload.cardY}px`;
      tip.style.width = `${payload.cardW || MENU_W + 20}px`;
      tip.style.height = `${payload.cardH || 0}px`;
    }
    if (payload.pointerAt != null) tipMenuPointer = payload.pointerAt;
    const off = `${Math.max(10, tipMenuPointer - 8)}px`;
    if (payload.arrow === "up" || payload.arrow === "down") {
      ptr.style.marginLeft = off;
      ptr.style.marginTop = "";
    } else {
      ptr.style.marginTop = off;
      ptr.style.marginLeft = "";
    }
    ptr.style.alignSelf = "flex-start";
    return;
  }
  resetTipLayout();
  if (ptr) {
    ptr.style.marginTop = "";
    ptr.style.marginLeft = "";
    ptr.style.alignSelf = "";
  }
  if (payload.kind === "update") {
    const card = document.getElementById("tip-card");
    card.dataset.resetId = "";
    card.classList.remove("menu-card");
    card.classList.add("update-only");
    card.innerHTML = `<button type="button" class="update-link" data-open-release="1">${t().updateLine(
      payload.latest
    )}</button>`;
    document.getElementById("tip").className =
      "tip arrow-" + (payload.arrow || "right") + (tipHot ? " hot" : "");
    return;
  }
  if (!payload.snap) return;
  const snap = payload.snap;
  const spec = ICONS[snap.id];
  if (!spec) return;
  const rule = spec.evenOdd ? 'fill-rule="evenodd"' : "";
  const metricsHtml = !snap.metrics?.length
    ? `<div class="empty">${localizeError(snap)}</div>`
    : snap.metrics
        .map((m, i) => {
          const color = usageColor(m.percent);
          return `<div class="metric">
            <div class="metric-top"><span>${localizeMetricLabel(m.label)}</span><span class="metric-reset">${payload.resets?.[i] || ""}</span></div>
            <div class="track"><div class="fill" style="width:${Math.min(Math.max(m.percent, 0), 100)}%;background:${color}"></div></div>
            <div class="used">${usedText(m.percent)}</div>
          </div>`;
        })
        .join("");
  const notice = payload.resetNotice || snap.resetNotice;
  const banner = notice
    ? `<div class="reset-banner"><div class="reset-title">${t().resetTitle}</div></div>`
    : "";
  const close = notice
    ? `<button type="button" class="tip-close" data-close-reset="${snap.id}" aria-label="Close">×</button>`
    : "";
  const card = document.getElementById("tip-card");
  card.dataset.resetId = notice ? snap.id : "";
  card.classList.remove("update-only");
  card.classList.remove("menu-card");
  card.innerHTML = `
    ${close}
    <div class="card-head">
      <svg class="mini glyph" viewBox="${spec.viewBox}">${spec.d.map((p) => `<path ${rule} d="${p}"/>`).join("")}</svg>
      <div class="title">${usageTitle(snap.id)}</div>
    </div>${banner}${metricsHtml}`;
  document.getElementById("tip").className =
    "tip arrow-" + (payload.arrow || "right") + (tipHot ? " hot" : "");
}

