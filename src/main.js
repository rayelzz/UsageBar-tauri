function paintShownPercents() {
  const root = document.getElementById("cells");
  if (!root) return;
  const items = root.querySelectorAll("[data-id]");
  if (!items.length) {
    renderBar();
    return;
  }
  items.forEach((el) => {
    const snap = snaps.find((s) => s.id === el.dataset.id);
    if (!snap) return;
    const unknown = snap.headlinePercent == null;
    const shown = shownPct(snap.headlinePercent);
    const pctEl = el.querySelector(".pct");
    if (pctEl) pctEl.textContent = unknown || shown == null ? "—" : `${Math.round(shown)}%`;
    const ring = el.querySelector("circle:not(.ring-track-outer):not(.ring-track-inner)");
    if (ring && !unknown && shown != null) {
      const r = Number(ring.getAttribute("r"));
      if (r > 0) {
        const circ = 2 * Math.PI * r;
        const dash = (Math.min(Math.max(shown, 0), 100) / 100) * circ;
        ring.setAttribute("stroke-dasharray", `${dash} ${circ}`);
      }
    }
  });
  paintInkChrome();
}

function applyIncomingSnap(snap) {
  if (!snap?.id) return;
  const next = applyNoticeAcks({ ...snap, loading: false });
  snaps = snaps.map((s) => (s.id === next.id ? next : s));
  const el = document.querySelector(`#cells [data-id="${next.id}"]`);
  if (!el) {
    renderBar();
  } else {
    el.classList.toggle("unknown", next.headlinePercent == null);
    el.classList.toggle("reset", !!(next.resetNotice || next.creditNotice));
    paintShownPercents();
  }
  if (hovered === next.id) renderTip().catch((err) => console.error(err));
}

async function finishRefreshPaint() {
  if (hovered && !snaps.some((s) => s.id === hovered)) {
    await setHovered(null);
  }
  renderBar();
  if (menuOpen || dragging) return;
  if (resetToastId) {
    const current = snaps.find((s) => s.id === resetToastId);
    if (current?.resetNotice) {
      hovered = resetToastId;
      await renderTip();
      return;
    }
    resetToastId = null;
    await setTipClickable(false);
  }
  if (creditToastId) {
    const current = snaps.find((s) => s.id === creditToastId);
    if (current?.creditNotice) {
      hovered = creditToastId;
      await renderTip();
      return;
    }
    clearCreditToastTimer();
    creditToastId = null;
    await setTipClickable(false);
  }
  if (await maybeShowResetToast()) return;
  if (await maybeShowCreditToast()) return;
  if (hovered) await renderTip();
  else await showUpdateToast();
}

async function refresh() {
  if (refreshing) {
    refreshQueued = true;
    return;
  }
  refreshing = true;
  try {
    do {
      refreshQueued = false;
      const gen = ++refreshGen;
      snaps = snaps.map((s) => (hasMetrics(s) ? s : { ...s, loading: true }));
      renderBar();
      if (hovered) await renderTip();
      let got = null;
      try {
        got = await invoke("fetch_usage");
      } catch (err) {
        console.error(err);
        if (gen !== refreshGen) continue;
        snaps = snaps.map((s) =>
          hasMetrics(s) ? { ...s, loading: false } : { ...s, loading: false, error: s.error || "api_error" }
        );
      }
      if (gen !== refreshGen) continue;
      if (Array.isArray(got)) {
        snaps = slotsFrom(got).map((s) => ({ ...s, loading: false }));
      }
      await finishRefreshPaint();
    } while (refreshQueued);
  } finally {
    refreshing = false;
  }
}

