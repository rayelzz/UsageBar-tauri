function formatReset(ms) {
  if (ms == null) return "";
  const d = new Date(ms);
  if (Number.isNaN(d.getTime())) return "";
  let h = d.getHours();
  const m = String(d.getMinutes()).padStart(2, "0");
  const day = t().days[d.getDay()];
  if (isZh()) {
    const ap = h < 12 ? "上午" : "下午";
    h = h % 12;
    if (h === 0) h = 12;
    return `重置 ${day} ${ap} ${h}:${m}`;
  }
  const ap = h < 12 ? "AM" : "PM";
  h = h % 12;
  if (h === 0) h = 12;
  return `Resets ${day} ${h}:${m} ${ap}`;
}

