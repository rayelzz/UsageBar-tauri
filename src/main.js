async function handleMenuAction(id) {
  if (!id) return;
  if (id === "close") {
    await closeMenuPanel();
    return;
  }
  if (id === "checkupdate") {
    if (menuInstalling) return;
    await checkUpdateManual();
    return;
  }
  if (id === "update" || id === "latest") {
    await installAvailableUpdate();
    return;
  }
  if (id === "refresh") {
    await closeMenuPanel();
    refresh().catch((err) => console.error(err));
    return;
  }
  if (id === "tools" || id === "quit") {
    await closeMenuPanel();
    await onNativeMenu(id);
    return;
  }
  if (id.startsWith("snap:")) {
    await onNativeMenu(id);
    if (menuOpen) await showPanelMenu(true);
    return;
  }
  if (id.startsWith("style:")) {
    await onNativeMenu(id);
    if (menuOpen) await showPanelMenu(false);
    return;
  }
  if (MENU_TOGGLES.has(id)) {
    await onNativeMenu(id);
    if (menuOpen) await showPanelMenu(false);
    return;
  }
  if (id.startsWith("interval:")) {
    prefs.refreshInterval = Number(id.slice(9));
    restartTimer();
    savePrefs().catch((err) => console.error(err));
    return;
  }
  if (id.startsWith("value:")) {
    setDisplayValue(id.slice(6));
    return;
  }
  if (id.startsWith("locale:")) {
    await setLocale(id.slice(7));
    if (menuOpen) await showPanelMenu(false);
    return;
  }
  await onNativeMenu(id);
  if (menuOpen) await showPanelMenu(false);
}

async function applyLayout(payload) {
  if (!payload) return;
  const edgeChanged = payload.edge && payload.edge !== prefs.edge;
  if (payload.edge) prefs.edge = payload.edge;
  if (typeof payload.along === "number") prefs.along = payload.along;
  if (typeof payload.floatingX === "number") prefs.floatingX = payload.floatingX;
  if (typeof payload.floatingY === "number") prefs.floatingY = payload.floatingY;
  if (typeof payload.screenName === "string") prefs.screenName = payload.screenName;
  if (typeof payload.lastX === "number") prefs.lastX = payload.lastX;
  if (typeof payload.lastY === "number") prefs.lastY = payload.lastY;
  dragging = !!payload.dragging;
  document.documentElement.classList.toggle("dragging", dragging);
  if (dragging) await setHovered(null);
  setBarHot();
  if (edgeChanged) {
    renderBar();
    if (!dragging) await placeWindows();
  }
}

async function startBar() {
  document.getElementById("bar-root").hidden = false;
  osName = await invoke("os_name");
  prefs = normalizeLoadedPrefs(await invoke("get_prefs"));
  prefsReady = true;
  snaps = slotsFrom([], true);
  try {
    appVersion = await invoke("app_version");
  } catch {
    appVersion = "";
  }
  applyLocale();
  try {
    if (api().autostart) {
      prefs.launchAtLogin = await api().autostart.isEnabled();
    }
  } catch {
    /* plugin optional */
  }
  renderBar();
  await placeWindows();
  refresh().catch((err) => console.error(err));
  restartTimer();
  applyAutoUpdatePref();
  document.getElementById("gear-btn").addEventListener("pointerdown", (e) => {
    e.stopPropagation();
  });
  document.getElementById("gear-btn").addEventListener("click", (e) => {
    e.preventDefault();
    e.stopPropagation();
    if (menuOpen) closeMenuPanel().catch((err) => console.error(err));
    else showPanelMenu().catch((err) => console.error(err));
  });
  document.addEventListener("contextmenu", (e) => {
    e.preventDefault();
    if (!menuOpen) showPanelMenu().catch((err) => console.error(err));
  });
  document.addEventListener("pointerdown", (e) => {
    if (e.button === 0) invoke("set_pointer", { left: true }).catch(() => {});
  });
  document.addEventListener("pointerup", (e) => {
    if (e.button === 0) invoke("set_pointer", { left: false }).catch(() => {});
  });
  document.addEventListener("pointercancel", () => {
    invoke("set_pointer", { left: false }).catch(() => {});
  });
  await api().event.listen("usagebar-menu", (e) => {
    handleMenuAction(e.payload).catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-layout", (e) => {
    applyLayout(e.payload).catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-prefs", (e) => {
    if (!e.payload) return;
    const prev = (prefs.visibleProviders || []).join(",");
    const prevAuto = !!prefs.autoCheckUpdate;
    const prevValue = prefs.displayValue;
    const prevStyle = prefs.displayStyle;
    prefs = normalizeLoadedPrefs({ ...prefs, ...e.payload });
    applyLocale();
    if (prevAuto !== prefs.autoCheckUpdate) applyAutoUpdatePref();
    if (prev !== prefs.visibleProviders.join(",")) {
      snaps = slotsFrom(snaps.filter((s) => s.id), true);
      renderBar();
      placeWindows().catch((err) => console.error(err));
      refresh().catch((err) => console.error(err));
    } else if (prevValue !== prefs.displayValue || prevStyle !== prefs.displayStyle) {
      if (prevStyle !== prefs.displayStyle) {
        renderBar();
        placeWindows().catch((err) => console.error(err));
      } else {
        paintShownPercents();
      }
      if (hovered) renderTip().catch((err) => console.error(err));
    }
  });
  await api().event.listen("usagebar-over", (e) => {
    setBarHot(!!e.payload);
  });
  await api().event.listen("usagebar-tip-ready", (e) => resolveTipReady(e.payload));
  await api().event.listen("usagebar-hover", (e) => {
    if (menuOpen || dragging) {
      if (hovered) setHovered(null).catch((err) => console.error(err));
      return;
    }
    if (resetToastId) return;
    setHovered(e.payload || null).catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-reset-ack", (e) => {
    closeResetToast(e.payload).catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-update-open", () => {
    openUpdateFromPrompt().catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-update-progress", (e) => {
    const total = Number(e.payload?.total);
    const downloaded = Number(e.payload?.downloaded);
    if (!total || !Number.isFinite(downloaded)) return;
    const pct = Math.min(100, Math.round((downloaded / total) * 100));
    if (pct === menuInstallPercent) return;
    menuInstallPercent = pct;
    if (menuOpen) showPanelMenu(false).catch((err) => console.error(err));
  });
  await api().event.listen("usagebar-usage", (e) => {
    if (e.payload) applyIncomingSnap(e.payload);
  });
}

let lastMenuPointer = null;

function setMenuHover(el) {
  const root = document.getElementById("tip-root");
  if (!root) return;
  root.querySelectorAll(".m-row.is-hover, .m-chip.is-hover").forEach((n) => {
    if (n !== el) n.classList.remove("is-hover");
  });
  if (el && !el.classList.contains("dim")) el.classList.add("is-hover");
}

function paintChipSelection(el) {
  const id = el?.dataset?.mid || "";
  const prefix = id.split(":")[0];
  if (!["interval", "snap", "style", "value", "locale"].includes(prefix)) return;
  const root = el.closest("#tip-card") || document;
  root.querySelectorAll(`.m-chip[data-mid^="${prefix}:"]`).forEach((chip) => {
    chip.classList.toggle("on", chip === el);
  });
}

function menuItemFromPoint(x, y) {
  const stack = document.elementsFromPoint?.(x, y) || [];
  for (const node of stack) {
    const item = node.closest?.(".m-row, .m-chip");
    if (item && item.closest(".menu-card") && !item.classList.contains("dim")) return item;
  }
  return null;
}

function syncMenuHover(e) {
  if (e) lastMenuPointer = { x: e.clientX, y: e.clientY };
  const p = lastMenuPointer;
  setMenuHover(p ? menuItemFromPoint(p.x, p.y) : null);
}

function readTranslate(el) {
  const raw = getComputedStyle(el).transform;
  if (!raw || raw === "none") return { x: 0, y: 0 };
  try {
    const m = new DOMMatrixReadOnly(raw);
    return { x: m.m41, y: m.m42 };
  } catch {
    const parts = raw.match(/matrix\((.+)\)/);
    if (!parts) return { x: 0, y: 0 };
    const n = parts[1].split(",").map(Number);
    return { x: n[4] || 0, y: n[5] || 0 };
  }
}

function clearTipSlide() {
  const root = document.getElementById("tip-root");
  const mover = document.getElementById("tip-mover");
  root?.classList.remove("tip-slide-stage", "tip-pin-bottom");
  if (!mover) return;
  mover.style.transition = "none";
  mover.style.transform = "";
  mover.style.height = "";
  delete mover.dataset.sliding;
  document.getElementById("tip-card")?.classList.remove("tip-card-fade");
}

function applyTipSlide(s) {
  const root = document.getElementById("tip-root");
  const mover = document.getElementById("tip-mover");
  if (!root || !mover || !s) return;
  root.classList.add("tip-slide-stage");
  root.classList.toggle("tip-pin-bottom", s.pin === "bottom");
  const x = s.x;
  const y = s.pin === "bottom" ? 0 : s.y;
  const ease = "cubic-bezier(0.16, 1, 0.3, 1)";
  const placed = mover.dataset.sliding === "1";
  if (s.keep && placed) return;
  if (s.duration > 0 && placed) {
    const cur = readTranslate(mover);
    mover.style.transition = "none";
    mover.style.transform = `translate3d(${cur.x}px, ${cur.y}px, 0)`;
    mover.style.height = "";
    void mover.offsetWidth;
    requestAnimationFrame(() => {
      mover.style.transition = `transform ${s.duration}ms ${ease}`;
      mover.style.transform = `translate3d(${x}px, ${y}px, 0)`;
    });
    return;
  }
  mover.style.transition = "none";
  mover.style.transform = `translate3d(${x}px, ${y}px, 0)`;
  mover.style.height = "";
  mover.dataset.sliding = "1";
}

function resetTipLayout() {
  clearTipSlide();
  document.getElementById("tip-root")?.classList.remove("menu-backdrop");
  const tip = document.getElementById("tip");
  if (!tip) return;
  tip.style.left = "";
  tip.style.top = "";
  tip.style.width = "";
  tip.style.height = "";
}

function paintUsageCard(payload) {
  const snap = payload.snap;
  const spec = ICONS[snap.id];
  if (!spec) return;
  const rule = spec.evenOdd ? 'fill-rule="evenodd"' : "";
  const metricsHtml = !snap.metrics?.length
    ? `<div class="empty${isQuerying(snap) ? " querying" : ""}">${localizeError(snap)}</div>`
    : snap.metrics
        .map((m, i) => {
          const shown = shownPct(m.percent) ?? 0;
          const color = usageColor(m.percent);
          return `<div class="metric">
            <div class="metric-top"><span>${localizeMetricLabel(m.label)}</span><span class="metric-reset">${payload.resets?.[i] || ""}</span></div>
            <div class="track"><div class="fill" style="width:${Math.min(Math.max(shown, 0), 100)}%;background:${color}"></div></div>
            <div class="used">${quotaText(m.percent)}</div>
          </div>`;
        })
        .join("");
  const notice = payload.resetNotice || snap.resetNotice;
  const banner = notice
    ? `<div class="reset-banner"><div class="reset-title">${t().resetTitle}</div></div>`
    : "";
  const close = notice
    ? `<button type="button" class="tip-close" data-close-reset="${snap.id}" aria-label="Close">×</button>`
    : "";
  const credits = resetCreditsOf(snap);
  const creditsHtml = !credits.length
    ? ""
    : `<div class="credit-block">
      <div class="credit-head">${t().resetCards}<span class="credit-count">${t().resetCardCount(credits.length)}</span></div>
      ${credits
        .map(
          (c) => `<div class="credit-row">
            <span class="credit-title">${localizeResetCreditTitle(c.title)}</span>
            <span class="credit-exp">${formatCreditExpiry(c.expiresAt)}</span>
          </div>`
        )
        .join("")}
    </div>`;
  const card = document.getElementById("tip-card");
  card.dataset.resetId = notice ? snap.id : "";
  card.classList.remove("update-only", "menu-card", "tip-card-fade");
  card.innerHTML = `
    ${close}
    <div class="card-head">
      <svg class="mini glyph" viewBox="${spec.viewBox}">${spec.d.map((p) => `<path ${rule} d="${p}"/>`).join("")}</svg>
      <div class="title">${usageTitle(snap.id)}</div>
    </div>${banner}${metricsHtml}${creditsHtml}`;
  if (payload.fade) {
    void card.offsetWidth;
    card.classList.add("tip-card-fade");
  }
  const tip = document.getElementById("tip");
  tip.classList.remove("menu-tip", "update-only", "arrow-left", "arrow-right", "arrow-up", "arrow-down");
  tip.classList.add("tip", "arrow-" + (payload.arrow || "right"));
  tip.classList.toggle("hot", tipHot);
}

function paintTip(payload) {
  if (!payload?.show) {
    resetTipLayout();
    return;
  }
  prefs.locale = payload.locale === "zh" ? "zh" : "en";
  if (payload.displayValue) {
    prefs.displayValue = payload.displayValue === "remaining" ? "remaining" : "used";
  }
  applyLocale();
  const ptr = document.getElementById("tip-pointer");
  if (payload.kind === "menu") {
    clearTipSlide();
    const root = document.getElementById("tip-root");
    const tip = document.getElementById("tip");
    const card = document.getElementById("tip-card");
    root.classList.add("menu-backdrop");
    card.dataset.resetId = "";
    card.classList.add("menu-card");
    card.innerHTML = menuPanelHtml(payload.state);
    tip.className = "tip menu-tip arrow-" + (payload.arrow || "right");
    if (payload.cardX != null && payload.cardY != null) {
      tip.style.left = `${payload.cardX}px`;
      tip.style.top = `${payload.cardY}px`;
      tip.style.width = `${payload.cardW || MENU_W}px`;
      tip.style.height = `${payload.cardH || 0}px`;
    }
    if (ptr) {
      ptr.hidden = true;
      ptr.style.marginTop = "";
      ptr.style.marginLeft = "";
      ptr.style.alignSelf = "";
    }
    requestAnimationFrame(() => syncMenuHover());
    return;
  }
  if (payload.slide) {
    document.getElementById("tip-root")?.classList.remove("menu-backdrop");
    if (ptr) {
      ptr.hidden = false;
      ptr.style.marginTop = "";
      ptr.style.marginLeft = "";
      ptr.style.alignSelf = "";
    }
    applyTipSlide(payload.slide);
    paintUsageCard({ ...payload, fade: !!payload.slide.fade });
    emitTipReady();
    return;
  }
  resetTipLayout();
  if (ptr) {
    ptr.hidden = false;
    ptr.style.marginTop = "";
    ptr.style.marginLeft = "";
    ptr.style.alignSelf = "";
  }
  if (payload.kind === "update") {
    const card = document.getElementById("tip-card");
    card.dataset.resetId = "";
    card.classList.remove("menu-card");
    card.classList.add("update-only");
    card.innerHTML = `<button type="button" class="update-link" data-open-release="1">${t().updateLine(
      payload.latest
    )}</button>`;
    document.getElementById("tip").className =
      "tip arrow-" + (payload.arrow || "right") + (tipHot ? " hot" : "");
    return;
  }
  if (!payload.snap) return;
  paintUsageCard(payload);
}

