function waitTipReady() {
  return new Promise((resolve) => {
    let done = false;
    const finish = (payload) => {
      if (done) return;
      done = true;
      resolve(payload || null);
    };
    const timer = setTimeout(() => finish(null), 140);
    tipReadyResolvers.push((payload) => {
      clearTimeout(timer);
      finish(payload);
    });
  });
}

